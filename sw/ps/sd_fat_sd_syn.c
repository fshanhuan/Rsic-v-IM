/* =============================================================================
 * sw/ps/sd_fat_sd_syn.c -- 与 sd_fat_sd.c 完全相同，只是样本不用记录仪 MMIO
 * -----------------------------------------------------------------------------
 * 做法就一句 `#define SD_SYNTH_SAMPLES` 然后 include 本体，避免复制一份代码。
 *
 * 为什么需要这个变体：
 *   验"卡能不能写"和验"PL 记录仪出不出数据"是两件事。真卡插上那天，如果 PL
 *   没烧记录仪位流（或记录仪没再跑），读 0x4001_00xx 会触发数据中止，
 *   `sd_fat_sd.elf` 就会停在异常里 —— 那时就分不清是卡的问题还是 PL 的问题。
 *   用假样本（0x800 + 7i，和 PC 侧测试同一个公式）先证明卡能写，变量就只剩卡。
 *
 * 用法：
 *   powershell -NoProfile -File sw\build_ps_sd.ps1 -App sd_fat_sd_syn
 *   $env:SD_ELF='sw/build/ps/sd_fat_sd_syn.elf'; xsdb _diag\ps_run_sd.tcl
 * ============================================================================= */
#define SD_SYNTH_SAMPLES 1
#include "sd_fat_sd.c"
