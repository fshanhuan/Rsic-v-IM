/* =============================================================================
 * sw/ps/sd_crc.h -- SD 协议用的两个 CRC（抽出来是为了能做"已知答案"测试）
 * -----------------------------------------------------------------------------
 * 为什么单独放一个文件：
 *   CRC7 用在**命令帧**上，而 SD 卡只在初始化阶段（CMD0/CMD8）真的检查它。
 *   如果 CRC7 算错了，CMD0 不会把卡复位、CMD8 会被拒 —— 现象和"没插卡"一模一样，
 *   极难分辨。所以这段必须有**独立于自己实现**的验证。
 *
 *   这个文件不依赖任何硬件（只用 xil_types.h），因此可以：
 *     · 被 ARM 裸机程序（sd_bit_bus.c）用；
 *     · 被 PC 上的测试（tools/ps/host）编译并对照 SD 规范里公开的帧做已知答案检查。
 *
 * 参考值（SD 物理层规范里公开的帧，最后一个字节 = (crc7<<1)|1）：
 *   CMD0  : 40 00 00 00 00 **95**   -> crc7 = 0x4A
 *   CMD8  : 48 00 00 01 AA **87**   -> crc7 = 0x43
 *   CRC16 XMODEM 标准检查值 "123456789" -> 0x31C3
 * ============================================================================= */
#ifndef SD_CRC_H
#define SD_CRC_H

#include "xil_types.h"

/* SD 命令帧 CRC7：多项式 x^7 + x^3 + 1（0x09），初值 0，返回 7 位结果 */
u8  sd_crc7(const u8 *d, u32 n);

/* SD 数据块 CRC16：XMODEM 多项式 0x1021，初值 0 */
u16 sd_crc16(const u8 *d, u32 n);

#endif /* SD_CRC_H */
