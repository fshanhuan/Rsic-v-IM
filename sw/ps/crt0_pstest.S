/* =============================================================================
 * sw/ps/crt0_pstest.S — 最小启动桩（给 sw/pstest.c 用）
 * -----------------------------------------------------------------------------
 * 只做两件事：设栈、调 main。不需要清 .bss（pstest 的全局变量在 main 里显式赋值，
 * 而且 PS 装载时会显式把 .bss 清零）。
 * ============================================================================= */
    .section .text.start, "ax"
    .globl _start
_start:
    la      sp, _stack_top
    call    main
1:  j       1b
